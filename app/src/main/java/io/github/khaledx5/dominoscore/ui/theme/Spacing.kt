package io.github.khaledx5.dominoscore.ui.theme

import androidx.compose.ui.unit.dp

/** The spacing scale. Layouts pick from these steps instead of inventing new values. */
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Side padding of every screen. */
    val screenHorizontal = xl

    /** Height of the main call-to-action buttons. */
    val primaryButtonHeight = 56.dp
}
